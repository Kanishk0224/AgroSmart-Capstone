export const cropService = {
  async getAllCrops(filters?: { category?: string; soilType?: string; season?: string }): Promise<Crop[]> {
    try {
      const queryParams: Record<string, string> = {};
      if (filters?.category) queryParams.category = filters.category;
      if (filters?.soilType) queryParams.soilType = filters.soilType;
      if (filters?.season) queryParams.season = filters.season;

      const res = await apiClient.get<Crop[]>('crops', { params: queryParams });
      if (res && res.data && res.data.length > 0) {
        return res.data;
      }
    } catch {
      // Fallback to local verified catalog
    }

    return VERIFIED_CROP_CATALOG.filter((c) => {
      if (filters?.category && filters.category !== 'ALL' && c.category !== filters.category) {
        return false;
      }
      if (filters?.soilType && filters.soilType !== 'ALL' && !c.suitableSoilTypes.includes(filters.soilType)) {
        return false;
      }
      if (filters?.season && filters.season !== 'ALL' && !c.suitableSeasons.includes(filters.season as CropSeason)) {
        return false;
      }
      return true;
    });
  },

  async getCropById(cropId: string): Promise<Crop | null> {
    try {
      const res = await apiClient.get<Crop>(`crops/${cropId}`);
      if (res && res.data) return res.data;
    } catch {
      // Fallback
    }
    const found = VERIFIED_CROP_CATALOG.find(
      (c) => c.cropId.toLowerCase() === cropId.toLowerCase() || c.cropName.toLowerCase() === cropId.toLowerCase()
    );
    return found || null;
  },
};
